package com.campusnex;

import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import jakarta.servlet.http.HttpSession;

import java.io.IOException;
import java.time.ZoneId;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Request/response demonstration (laboratory experiment 8).
 * Reads the HTTP request (method, parameters, headers) and returns a JSON
 * description of what the server received together with a generated greeting.
 */
public class HelloServlet extends ApiServlet {

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp) throws ServletException, IOException {
        handle(req, resp);
    }

    @Override
    protected void doPost(HttpServletRequest req, HttpServletResponse resp) throws ServletException, IOException {
        handle(req, resp);
    }

    private void handle(HttpServletRequest req, HttpServletResponse resp) throws IOException {
        req.setCharacterEncoding("UTF-8");
        AtomicInteger requests = (AtomicInteger) getServletContext().getAttribute(AppStartListener.APP_REQUESTS);
        int requestNumber = requests == null ? -1 : requests.incrementAndGet();

        String name = clean(req.getParameter("name"), "Guest", 60);
        String message = clean(req.getParameter("message"), "", 200);

        Map<String, Object> params = new LinkedHashMap<>();
        req.getParameterMap().forEach((k, v) -> params.put(k, v.length == 1 ? v[0] : java.util.List.of(v)));

        Map<String, Object> headers = new LinkedHashMap<>();
        for (String h : new String[] {"User-Agent", "Accept", "Accept-Language", "Content-Type", "Origin", "Referer"}) {
            String value = req.getHeader(h);
            if (value != null) headers.put(h, value);
        }

        HttpSession session = req.getSession(false);
        ZonedDateTime now = ZonedDateTime.now(ZoneId.of("Asia/Kolkata"));

        Map<String, Object> body = new LinkedHashMap<>();
        body.put("servlet", getClass().getName());
        body.put("method", req.getMethod());
        body.put("requestUri", req.getRequestURI());
        body.put("queryString", req.getQueryString());
        body.put("protocol", req.getProtocol());
        body.put("contentLength", req.getContentLengthLong());
        body.put("parameters", params);
        body.put("headers", headers);
        body.put("remoteAddr", req.getRemoteAddr());
        body.put("serverInfo", getServletContext().getServerInfo());
        body.put("contextPath", req.getContextPath());
        body.put("sessionExists", session != null);
        body.put("thread", Thread.currentThread().getName());
        body.put("requestNumberSinceStart", requestNumber);
        body.put("serverTimeIST", now.format(DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss 'IST'")));
        body.put("greeting", "Hello, " + name + "! This response was generated by a Java Servlet on "
                + getServletContext().getServerInfo() + ".");
        if (!message.isEmpty()) body.put("echo", message);

        resp.setHeader("X-Served-By", "CampusNex HelloServlet");
        json(resp, HttpServletResponse.SC_OK, body);
    }

    private static String clean(String value, String fallback, int max) {
        if (value == null) return fallback;
        String v = value.strip();
        if (v.isEmpty()) return fallback;
        return v.length() > max ? v.substring(0, max) : v;
    }
}
