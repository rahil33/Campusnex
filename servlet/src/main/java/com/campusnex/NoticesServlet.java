package com.campusnex;

import jakarta.servlet.ServletException;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;
import java.io.PrintWriter;
import java.time.DayOfWeek;
import java.time.ZoneId;
import java.time.ZonedDateTime;
import java.time.format.DateTimeFormatter;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * Static-to-dynamic demonstration (laboratory experiment 10).
 * Returns an HTML fragment whose content depends on the current time, the
 * day of the week and the name supplied in the request. The browser inserts
 * the fragment into an otherwise static page.
 */
public class NoticesServlet extends ApiServlet {

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp) throws ServletException, IOException {
        String name = req.getParameter("name");
        name = (name == null || name.isBlank()) ? "Student" : name.strip();
        if (name.length() > 60) name = name.substring(0, 60);

        ZonedDateTime now = ZonedDateTime.now(ZoneId.of("Asia/Kolkata"));
        int hour = now.getHour();
        String part = hour < 12 ? "morning" : (hour < 17 ? "afternoon" : "evening");
        boolean sunday = now.getDayOfWeek() == DayOfWeek.SUNDAY;
        boolean weekend = sunday || now.getDayOfWeek() == DayOfWeek.SATURDAY;

        AtomicInteger counter = (AtomicInteger) getServletContext().getAttribute(AppStartListener.APP_REQUESTS);
        int n = counter == null ? -1 : counter.incrementAndGet();

        resp.setContentType("text/html;charset=UTF-8");
        resp.setHeader("Cache-Control", "no-store");
        resp.setHeader("X-Served-By", "CampusNex NoticesServlet");
        try (PrintWriter out = resp.getWriter()) {
            out.println("<article class=\"servlet-fragment\">");
            out.println("<h4>Good " + part + ", " + Json.html(name) + "</h4>");
            out.println("<p>Generated by <code>NoticesServlet</code> at "
                    + now.format(DateTimeFormatter.ofPattern("EEEE, dd MMM yyyy, HH:mm:ss 'IST'"))
                    + " (servlet request #" + n + " since the application started).</p>");
            out.println("<ul>");
            out.println("<li>Central Library: " + (sunday ? "closed today (sample hours)" : "open 08:30 to 20:00 (sample hours)") + "</li>");
            out.println("<li>Cafeteria: " + (weekend ? "weekend menu, 09:00 to 17:00 (sample)" : "full menu, 08:00 to 19:00 (sample)") + "</li>");
            out.println("<li>Computer Laboratory: " + (weekend ? "open by prior booking only (sample)" : "open 09:00 to 17:00 (sample)") + "</li>");
            out.println("</ul>");
            out.println("<p class=\"fine\">Reload to see the timestamp and request number change: the page is not stored, it is built per request.</p>");
            out.println("</article>");
        }
    }
}
